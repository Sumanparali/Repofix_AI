from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from sqlalchemy import create_engine, text


@dataclass(frozen=True)
class Job:
    id: int
    repository: str
    issue: str
    status: str
    result: dict
    created_at: str
    user_id: str = "local-dev"


def database_url(value: str | Path) -> str:
    raw = str(value)
    return raw if "://" in raw else f"sqlite:///{Path(raw).resolve().as_posix()}"


class JobStore:
    """Job persistence shared by SQLite tests and PostgreSQL deployments."""

    def __init__(self, database: str | Path = Path("repofix.db")) -> None:
        self.database = str(database)
        self.engine = create_engine(database_url(database), pool_pre_ping=True)
        self._initialize()

    def _initialize(self) -> None:
        with self.engine.begin() as connection:
            connection.execute(text("""CREATE TABLE IF NOT EXISTS users (
                id VARCHAR(128) PRIMARY KEY, email VARCHAR(320),
                display_name VARCHAR(160), created_at VARCHAR(40) NOT NULL)"""))
            postgres = """CREATE TABLE IF NOT EXISTS jobs (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id VARCHAR(128) NOT NULL DEFAULT 'local-dev', repository TEXT NOT NULL,
                issue TEXT NOT NULL, status VARCHAR(32) NOT NULL,
                result TEXT NOT NULL, created_at VARCHAR(40) NOT NULL)"""
            sqlite = """CREATE TABLE IF NOT EXISTS jobs (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id VARCHAR(128) NOT NULL DEFAULT 'local-dev', repository TEXT NOT NULL,
                issue TEXT NOT NULL, status VARCHAR(32) NOT NULL,
                result TEXT NOT NULL, created_at VARCHAR(40) NOT NULL)"""
            connection.execute(text(postgres if self.engine.dialect.name == "postgresql" else sqlite))
            if self.engine.dialect.name == "sqlite":
                columns = {row[1] for row in connection.exec_driver_sql("PRAGMA table_info(jobs)")}
                if "user_id" not in columns:
                    connection.exec_driver_sql(
                        "ALTER TABLE jobs ADD COLUMN user_id VARCHAR(128) NOT NULL DEFAULT 'local-dev'"
                    )

    def ensure_user(self, user_id: str, email: str | None, display_name: str | None) -> None:
        created = datetime.now(timezone.utc).isoformat()
        with self.engine.begin() as connection:
            existing = connection.execute(
                text("SELECT id FROM users WHERE id = :id"), {"id": user_id}
            ).first()
            values = {"id": user_id, "email": email, "name": display_name, "created": created}
            if existing:
                connection.execute(text(
                    "UPDATE users SET email=:email, display_name=:name WHERE id=:id"
                ), values)
            else:
                connection.execute(text(
                    "INSERT INTO users(id,email,display_name,created_at) "
                    "VALUES (:id,:email,:name,:created)"
                ), values)

    def create(
        self, repository: str, issue: str, status: str = "queued", user_id: str = "local-dev"
    ) -> Job:
        created = datetime.now(timezone.utc).isoformat()
        values = {"user": user_id, "repository": repository, "issue": issue,
                  "status": status, "result": "{}", "created": created}
        with self.engine.begin() as connection:
            statement = """INSERT INTO jobs(user_id,repository,issue,status,result,created_at)
                VALUES (:user,:repository,:issue,:status,:result,:created)"""
            if self.engine.dialect.name == "postgresql":
                identifier = connection.execute(text(statement + " RETURNING id"), values).scalar_one()
            else:
                identifier = connection.execute(text(statement), values).lastrowid
        return Job(int(identifier), repository, issue, status, {}, created, user_id)

    def update(self, identifier: int, status: str, result: dict) -> Job:
        with self.engine.begin() as connection:
            connection.execute(text(
                "UPDATE jobs SET status=:status,result=:result WHERE id=:id"
            ), {"status": status, "result": json.dumps(result), "id": identifier})
        job = self.get(identifier)
        if job is None:
            raise KeyError(identifier)
        return job

    def get(self, identifier: int, user_id: str | None = None) -> Job | None:
        query, values = "SELECT * FROM jobs WHERE id=:id", {"id": identifier}
        if user_id is not None:
            query += " AND user_id=:user"
            values["user"] = user_id
        with self.engine.connect() as connection:
            row = connection.execute(text(query), values).mappings().first()
        return _job(row) if row else None

    def list(self, limit: int = 100, user_id: str | None = None) -> list[Job]:
        query, values = "SELECT * FROM jobs", {"limit": limit}
        if user_id is not None:
            query += " WHERE user_id=:user"
            values["user"] = user_id
        query += " ORDER BY id DESC LIMIT :limit"
        with self.engine.connect() as connection:
            rows = connection.execute(text(query), values).mappings().all()
        return [_job(row) for row in rows]


def _job(row) -> Job:
    return Job(int(row["id"]), row["repository"], row["issue"], row["status"],
               json.loads(row["result"]), row["created_at"], row.get("user_id") or "local-dev")
